# ---------------------------------------------------------------------------
# Deterministic seed generation
# ---------------------------------------------------------------------------

def _derive_seed(brief: CampaignBrief, product: ShopeeProduct) -> int:
    """Derive a deterministic int seed from the brief + product IDs.

    The seed is used as consistency_seed in AiShot; here it also provides
    repeatable shot ordering within a template.
    """
    raw = f"{brief.brief_id}:{product.item_id}:{product.shop_id}"
    digest = hashlib.sha256(raw.encode()).hexdigest()
    # Take the first 8 hex chars → 32-bit positive int
    return int(digest[:8], 16)


