"""Writers' Room — deterministic, offline-only storyboard builder (Phase 1).

Takes a CampaignBrief and ShopeeProduct and produces a schema-valid
Storyboard (v1) ready for the Editor agent. FR-WR-01..04:

  - Hook scene <= 2.0s
  - Body scenes: avg 1.0-5.0s per Storyboard._avg_shot_in_band
  - CTA scene is last
  - All 6 REQUIRED_EDITOR_PASSES present
  - Total duration <= 60s
  - Consistent consistency_seed across all AiShot siblings (if AiStoryboard
    is also generated by callers)

No LLM, no Anthropic, no httpx, no network calls.
"""

