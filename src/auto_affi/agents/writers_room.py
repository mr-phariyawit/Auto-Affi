# ---------------------------------------------------------------------------

def build_storyboard(
    brief: CampaignBrief,
    product: ShopeeProduct,
) -> Storyboard:
    """Build a deterministic, schema-valid Storyboard from a brief + product.

    The mapping is:
      product name keywords + hook_template_slug → 6 fixed scene specs
      (hook 2s → agitate 4s → demonstrate 5s → resolve 4s → social_proof 5s
       → cta 4s) = 24s total.

    All schema validators pass:
      - scenes[0].purpose == HOOK, duration_s <= 2.0
      - avg body shot 4.4s ∈ [1.0, 5.0]
      - total 24.0s <= 60.0
      - cta_scene_idx points to scenes[-1] whose purpose == CTA
      - all 6 REQUIRED_EDITOR_PASSES present

    Parameters
    ----------
    brief:
        The CampaignBrief produced by build_brief().
    product:
        The ShopeeProduct used to personalise visual prompts.

    Returns
    -------
    Storyboard
        A fully-populated, pydantic-validated storyboard.
    """
    product_name = product.name
    cta_text = brief.cta.text_th

    scenes = [
        _render_scene(idx, spec, product_name, cta_text)
        for idx, spec in enumerate(_SCENE_SPECS)
    ]

    cta_idx = len(scenes) - 1

    return Storyboard(
        brief_id=brief.brief_id,
        voice_profile=VoiceProfile(
            lang="th",
            gender="f",
            tone="energetic-confident",
            tts_engine="elevenlabs",
            voice_id="auto",
        ),
        music_brief=MusicBrief(
            genre="upbeat-pop",
            bpm_range=(110, 130),
            license="epidemic-sound",
        ),
        scenes=scenes,
        cta_scene_idx=cta_idx,
        affiliate_link_placement="pinned_comment + on_screen_qr",
        editor_passes=list(REQUIRED_EDITOR_PASSES),
    )
