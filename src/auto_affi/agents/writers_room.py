def _render_scene(
    idx: int,
    spec: _SceneSpec,
    product_name: str,
    cta_text: str,
    generator: str = "sora2",
) -> Scene:
    """Instantiate a Scene from a _SceneSpec with substituted text."""
    vprompt = spec.visual_prompt_template.format(product_name=product_name)
    dialogue_th = spec.dialogue_th_template.format(
        product_name=product_name, cta_text=cta_text
    )
    on_screen_th = spec.on_screen_th_template.format(
        product_name=product_name, cta_text=cta_text
    )
    return Scene(
        idx=idx,
        duration_s=spec.duration_s,
        purpose=spec.purpose,
        shot_type=spec.shot_type,
        movement=spec.movement,
        visual_prompt=vprompt,
        generator=generator,
        dialogue=Dialogue(
            speaker="narrator",
            text_th=dialogue_th[:300],
            emphasis_words=[],
        ),
        on_screen_text=OnScreenText(
            th=on_screen_th[:120],
            style="bold-pop",
            position="center-upper",
        ),
        sfx=list(spec.sfx),
        transition_out=spec.transition_out,
    )


